#!/usr/bin/env node
// Tests of the lookup's part for PyPI (lookup-pypi.mjs, run by lookup.mjs; #716): each package name invented, each
// answer of PyPI recorded in the shape it gives, trimmed to what the lookup reads, and handed to it in place of the
// network (floor rule 8: no live call, no real package): what a requirements file in PyPI's lock form holds, what PyPI
// says, and the check run on a project whose licence config names one under "pypi". Run: node tests/lookup-pypi-test.mjs
import { execFileSync } from "node:child_process";
import { rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { lookUp, run, YOUNG } from "../scripts/lookup.mjs";
import { pep440, pypiPackages } from "../scripts/lookup-pypi.mjs";
import { INVENTED_SUM, NOW, ago, tgz } from "../scripts/lookup-stage.mjs";
import { mended } from "../scripts/mend.mjs";
import { scratchDir } from "../scripts/scratch-core.mjs";

let failed = 0;
const ok = (cond, what) => { if (!cond) { failed++; console.error(`FAIL ${what}`); } };
const throws = (f) => { try { f(); return ""; } catch (e) { return e.message; } };

// (a hash of PyPI's form, its bytes invented)
const H = (c = "a") => `--hash=sha256:${c.repeat(64)}`;

// ---- What a requirements file holds
const compiled = [
  "#", "# This file is autogenerated by pip-compile with Python 3.12", "# by the following command:", "#",
  "#    pip-compile --generate-hashes requirements.in", "#",
  `Tidy_Moss.Format[extra]==1.1.0 ; python_version >= "3.10" \\`, `    ${H("a")} \\`, `    ${H("b")}`,
  "    # via -r requirements.in",
  `brand-new-moss==1.1.0 \\`, `    ${H("c")}`,
  "    # via", "    #   tidy-moss-format",
  `deep-moss==2.0.0 \\`, `    ${H("d")}`,
  "    # via brand-new-moss",
  `own-moss==1.0.0 ${H("e")}`,
  "    # via invented-project (pyproject.toml)",
].join("\n");
const read = pypiPackages(compiled, "requirements.txt");
const by = (name) => read.find((p) => p.name === name);
ok(read.length === 4 && read.every((p) => p.pypi) && by("tidy-moss-format")?.version === "1.1.0", `its packages read, each name as pip compares it, an extra and a marker left aside (${read.map((p) => p.name)})`);
ok(by("tidy-moss-format")?.direct === true && by("tidy-moss-format")?.brings === 2, "a package the project's own file names is named by it, and brings what its \"# via\" lines say, deep too");
ok(by("brand-new-moss")?.direct === false && by("brand-new-moss")?.by.join() === "tidy-moss-format" && by("deep-moss")?.by.join() === "tidy-moss-format", "a package another brings names the one the project names that brings it");
ok(by("own-moss")?.direct === true, "a \"# via\" line that names the project itself, no package of the file, is named by the project");
const plain = pypiPackages(`﻿plain-moss==1.0.0 ${H()}\r\nother-moss==2.0.0 ${H("b")} ${H("c")}\r\n`, "requirements.txt");
ok(plain.length === 2 && plain.every((p) => p.direct && p.brings === null), `a file with no "# via" line names every package itself, and says nothing of what each brings (${JSON.stringify(plain)})`);
const separated = ["\r", "\v", "\f", "\x1c", "\x1d", "\x1e", "\x85", "\u2028", "\u2029"].map((sep) => pypiPackages(`# a note${sep}hidden-moss==1.0.0 ${H()}`, "r.txt").map((p) => p.name).join());
ok(separated.every((n) => n === "hidden-moss"), `a line ends at each separator pip ends one at, a lone carriage return among them, so no package hides behind a comment (${separated})`);
const declared = pypiPackages(`# -*- coding: utf-8 -*-\n# vim: set fileencoding=UTF8 :\nplain-moss==1.0.0 ${H()}`, "r.txt").map((p) => p.name).join();
ok(declared === "plain-moss", `a file that declares UTF-8 is read (${declared})`);
const joined = pypiPackages(`# a note that ends so \\\nhidden-moss==1.0.0 ${H()}\nsplit-\\\nmoss==1.0.0 \\\n  ${H()}\n`, "r.txt");
ok(joined.map((p) => p.name).join() === "hidden-moss,split-moss", `lines join as pip joins them: a comment ending in "\\" takes no package with it, and a package's name runs on unbroken (${joined.map((p) => p.name)})`);
ok(pypiPackages(`--require-hashes\n--index-url https://pypi.org/simple\nplain-moss==1.0.0 ${H()}`, "r.txt").length === 1, "an option that changes neither what is installed nor where from passes");
for (const [what, text, said] of [
  ["a range", `ranged-moss>=1.0 ${H()}`, /line 1: a package not at one exact version/u],
  ["a wildcard", `star-moss==1.* ${H()}`, /line 1: a package not at one exact version/u],
  ["an address", `addressed-moss @ https://example.invalid/addressed-moss-1.0.tar.gz ${H()}`, /line 1: a package not at one exact version/u],
  ["no hash", "\nbare-moss==1.0.0", /line 2: bare-moss names no hash/u],
  ["a hash pip does not check", "md5-moss==1.0.0 --hash=md5:0123456789abcdef0123456789abcdef", /names no hash/u],
  ["an include", `-r other.txt\nplain-moss==1.0.0 ${H()}`, /line 1: an option the lookup does not read/u],
  ["another index", `--extra-index-url https://example.invalid/simple\nplain-moss==1.0.0 ${H()}`, /line 1: an option/u],
  ["an editable package", "-e ./local", /line 1: an option/u],
  ["another encoding declared", `# coding: utf-7\n# note+AAo-hidden-moss==1.0.0 ${H()}`, /line 1: an encoding other than UTF-8 declared/u],
  ["another encoding declared on its second line", `#!/usr/bin/env pip\n# -*- coding: latin-1 -*-\nplain-moss==1.0.0 ${H()}`, /line 2: an encoding other than UTF-8 declared/u],
  ["a mark of UTF-16", `\uFFFD\uFFFDp\0l\0`, /line 1: bytes that are not UTF-8, or a NUL/u],
  ["a NUL", `plain-moss==1.0.0 ${H()}\n\0`, /line 2: bytes that are not UTF-8, or a NUL/u],
]) {
  const message = throws(() => pypiPackages(text, "requirements.txt"));
  ok(said.test(message) && mended(`FAIL: ${message}`) && /^requirements\.txt, line/u.test(message), `a file with ${what} is refused whole, saying the mend (${message})`);
}

// ---- What PyPI says
const file = (name, v, at, extra = {}) => ({ filename: `${name.replaceAll("-", "_")}-${v}-py3-none-any.whl`, upload_time_iso_8601: at, yanked: false, ...extra });
const doc = (name, first, extra = {}) => ({
  info: { name, project_urls: { Homepage: "https://example.invalid/", "Source Code": `https://github.com/invented-org/${name}` } },
  ownership: { organization: null, roles: [{ role: "Owner", user: "invented-owner" }] },
  releases: { "1.0.0": [file(name, "1.0.0", first)], "1.1.0": [file(name, "1.1.0", first > ago(30) ? first : ago(30))], "2.0.0": [file(name, "2.0.0", ago(3), { yanked: true })] },
  ...extra,
});
const integrity = (name, v) => `https://pypi.org/integrity/${name}/${v}/${name.replaceAll("-", "_")}-${v}-py3-none-any.whl/provenance`;
const answers = {
  "https://pypi.org/pypi/tidy-moss-format/json": { status: 200, json: doc("tidy-moss-format", ago(800)) },
  [integrity("tidy-moss-format", "1.1.0")]: { status: 200, json: { version: 1, attestation_bundles: [{ publisher: { kind: "GitHub", repository: "invented-org/tidy-moss-format", workflow: "release.yml" } }] } },
  "https://pypi.org/pypi/brand-new-moss/json": { status: 200, json: doc("brand-new-moss", ago(12)) },
  "https://pypi.org/pypi/elsewhere-moss/json": { status: 200, json: doc("elsewhere-moss", ago(400)) },
  [integrity("elsewhere-moss", "1.1.0")]: { status: 200, json: { attestation_bundles: [{ publisher: { kind: "GitHub", repository: "someone-else/fork" } }] } },
  "https://pypi.org/pypi/yanked-moss/json": { status: 200, json: doc("yanked-moss", ago(400), { ownership: {}, info: { author: "Invented Author" } }) },
  "https://pypi.org/pypi/empty-moss/json": { status: 200, json: { info: {}, releases: { "1.0.0": [] } } },
  "https://pypi.org/pypi/listless-moss/json": { status: 200, json: { info: {} } },
  "https://pypi.org/pypi/flaky-moss/json": { status: 503 },
  "https://api.github.com/repos/invented-org/tidy-moss-format": { status: 200, json: { archived: false } },
};
const asked = [];
const get = async (url) => { asked.push(url); return answers[url] ?? { status: 404 }; };
const pkg = (name, extra = {}) => ({ name, version: "1.1.0", path: name, direct: true, brings: null, pypi: true, lockPath: "requirements.txt", ...extra });
const one = async (p) => lookUp([p], { get, now: NOW });

let r = await one(pkg("tidy-moss-format", { brings: 2 }));
const report = r.reports[0] ?? "";
ok(r.failures.length === 0 && r.reports.length === 1, `an old package that exists passes (${JSON.stringify(r)})`);
for (const fact of ["named by the project", `first published ${ago(800).slice(0, 10)} (800 days ago)`, `last release ${ago(30).slice(0, 10)}`, "repository github.com/invented-org/tidy-moss-format, not archived", "published by owners invented-owner (as PyPI lists them)", "brings 2 packages with it", "provenance: yes, from GitHub invented-org/tidy-moss-format (release.yml), the repository it names"])
  ok(report.includes(fact), `the report says "${fact}" (${report})`);
ok(!asked.some((u) => new URL(u).hostname === "raw.githubusercontent.com"), "no package.json is asked of a PyPI package's repository");
r = await one(pkg("Tidy_Moss.Format"));
ok(r.failures.length === 0 && asked.some((u) => u === "https://pypi.org/pypi/tidy-moss-format/json"), "a name is asked as pip compares it");
r = await one(pkg("elsewhere-moss"));
ok(r.failures.length === 0 && /provenance: yes, from GitHub someone-else\/fork, not the repository it names/u.test(r.reports[0] ?? ""), `an attestation from another repository than the one it names is said so (${r.reports})`);
r = await one(pkg("yanked-moss", { version: "2.0.0", brings: 0 }));
ok(r.failures.length === 0 && /Invented Author \(as the package writes its authors\)/u.test(r.reports[0] ?? "") && /provenance: no file of this version to ask; this version is yanked/u.test(r.reports[0] ?? "") && r.reports[0].includes(`last release ${ago(30).slice(0, 10)}`), `a yanked version is said so, its date no last release, and with no owners listed the authors are named (${r.reports})`);
r = await one(pkg("never-published-moss"));
ok(r.failures.length === 1 && /PyPI has no such package/u.test(r.failures[0]) && mended(`FAIL: ${r.failures[0]}`), `a name PyPI does not know fails, saying the mend (${r.failures})`);
r = await one(pkg("tidy-moss-format", { version: "9.9.9" }));
ok(r.failures.length === 1 && /no file of version 9\.9\.9 of it/u.test(r.failures[0]), `a version PyPI does not hold fails (${r.failures})`);
ok(["1.0", "v1.0.0", "1.0.0.0"].every((v) => pep440(v) === pep440("1.0.0")) && pep440("1.0-1") === pep440("1.0.post1") && pep440("1.0c1") === pep440("1.0rc1") && pep440("1.0.post1") !== pep440("1.0") && pep440("1!1.0") !== pep440("1.0") && pep440("not a version") === null, "versions compare as PEP 440 holds them equal, and only so");
for (const v of ["1.1", "v1.1.0"]) {
  asked.length = 0;
  r = await one(pkg("tidy-moss-format", { version: v }));
  ok(r.failures.length === 0 && asked.includes(integrity("tidy-moss-format", "1.1.0")), `a version written ${v} finds PyPI's 1.1.0, and asks its provenance as PyPI keys it (${r.failures})`);
}
r = await one(pkg("empty-moss", { version: "1.0.0" }));
ok(r.failures.length === 1 && /holds no file of it/u.test(r.failures[0]), `a name registered with no file fails (${r.failures})`);
const comes = new Date(NOW + (YOUNG - 12) * 86400000).toISOString().slice(0, 10);
r = await one(pkg("brand-new-moss"));
ok(r.failures.length === 1 && r.failures[0].includes(`12 days ago, under the ${YOUNG} days`) && r.failures[0].includes(`wait until ${comes}`) && mended(`FAIL: ${r.failures[0]}`), `a package first published under ${YOUNG} days ago fails, saying the day it may come (${r.failures})`);
r = await one(pkg("brand-new-moss", { direct: false, by: ["tidy-moss-format"] }));
ok(r.failures.length === 1 && r.failures[0].includes("hold the change that brings it (to tidy-moss-format)"), `one that another brings names what brings it (${r.failures})`);
for (const name of ["flaky-moss", "listless-moss"]) {
  r = await one(pkg(name));
  ok(r.failures.length === 1 && /PyPI could not be read/u.test(r.failures[0]) && mended(`FAIL: ${r.failures[0]}`), `${name}: an answer PyPI does not give in its shape fails the lookup, saying the mend (${r.failures})`);
}
asked.length = 0;
r = await one(pkg("bad/../name"));
ok(r.failures.length === 1 && /not one PyPI gives/u.test(r.failures[0]) && !asked.length, "a name PyPI never gives is not asked of it");

// ---- The check on a project
const tmp = scratchDir("lookup-pypi-test-");
const git = (...args) => execFileSync("git", ["-c", "user.name=test", "-c", "user.email=test@example.invalid", "-c", "commit.gpgsign=false", ...args], { cwd: tmp, encoding: "utf8" }).trim();
try {
  git("init", "-q");
  const config = join(tmp, "licences.json");
  const settings = (pypi) => writeFileSync(config, JSON.stringify({ lockfiles: ["package-lock.json"], ships: [], ...(pypi ? { pypi } : {}) }));
  settings(["requirements.txt"]);
  writeFileSync(join(tmp, "package.json"), "{}");
  writeFileSync(join(tmp, "package-lock.json"), JSON.stringify({ lockfileVersion: 3, packages: { "": {}, "node_modules/tidy-moss-format": { version: "1.1.0", resolved: tgz("tidy-moss-format"), integrity: INVENTED_SUM } } }));
  writeFileSync(join(tmp, "requirements.txt"), `tidy-moss-format==1.1.0 ${H()}\n`);
  writeFileSync(join(tmp, "data.txt"), `never-published-moss==1.0.0 ${H()}\n`);
  git("add", "-A"); git("commit", "-qm", "base");
  const base = git("rev-parse", "HEAD"), npmGet = async (url) => (url.startsWith("https://registry.npmjs.org/") ? { status: 404 } : get(url));
  asked.length = 0;
  r = await run(config, { root: tmp, base, get: npmGet, now: NOW });
  ok(r.code === 0 && !asked.length && r.lines.includes("ok   0 new packages looked up in PyPI, each printed above for the review"), `what the base held is not looked up (${r.lines})`);
  writeFileSync(join(tmp, "requirements.txt"), `Tidy_Moss_Format==2.0.0 ${H()}\nnever-published-moss==1.0.0 ${H()}\n`);
  r = await run(config, { root: tmp, base, get: npmGet, now: NOW });
  let out = r.lines.join("\n");
  ok(r.code === 1 && mended(out) && /^FAIL: requirements\.txt: never-published-moss@1\.0\.0: PyPI has no such package/mu.test(out) && !/tidy-moss-format/u.test(out) && /1 of 1 new package fail/u.test(out) && /ok {3}0 new packages looked up in the npm registry/u.test(out), `an update passes unlooked, in any spelling, and a new name PyPI lacks fails, beside npm's lookup (${r.lines})`);
  writeFileSync(join(tmp, "requirements.txt"), `tidy-moss-format==1.1.0 ${H()}\n`);
  settings(["requirements.txt", "data.txt"]);
  r = await run(config, { root: tmp, base, get: npmGet, now: NOW });
  ok(r.code === 1 && /^FAIL: data\.txt: never-published-moss@1\.0\.0/mu.test(r.lines.join("\n")), `a file the pull request newly names under "pypi" makes no name held (${r.lines})`);
  for (const pypi of [null, []]) {
    settings(pypi);
    writeFileSync(join(tmp, "requirements.txt"), `tidy-moss-format==1.1.0 ${H()}\nnever-published-moss==1.0.0 ${H()}\n`);
    r = await run(config, { root: tmp, base, get: npmGet, now: NOW });
    ok(r.code === 1 && /^FAIL: requirements\.txt: never-published-moss@1\.0\.0/mu.test(r.lines.join("\n")), `a file the base's config named is read though the pull request takes it out of "pypi" (${JSON.stringify(pypi)}) (${r.lines})`);
  }
  writeFileSync(join(tmp, "requirements.txt"), `tidy-moss-format==1.1.0 ${H()}\n`);
  git("add", "-A"); git("commit", "-qm", "no pypi");
  r = await run(config, { root: tmp, base: git("rev-parse", "HEAD"), get: npmGet, now: NOW });
  ok(r.code === 0 && !r.lines.some((l) => /PyPI/u.test(l)), `a config that names no "pypi", nor its base's, asks nothing of PyPI, and says nothing of it (${r.lines})`);
  rmSync(join(tmp, "requirements.txt"));
  r = await run(config, { root: tmp, base, get: npmGet, now: NOW });
  ok(r.code === 0, `a file the base's config named, taken out of the project with its name, is not read (${r.lines})`);
  writeFileSync(join(tmp, "requirements.txt"), `tidy-moss-format==1.1.0 ${H()}\n`);
  writeFileSync(config, JSON.stringify({ ships: [], pypi: ["requirements.txt"] }));
  r = await run(config, { root: tmp, base, get: npmGet, now: NOW });
  ok(r.code === 0 && r.lines.includes("ok   0 new packages looked up in PyPI, each printed above for the review"), `a config that names PyPI's files alone, no lock file of npm's, is read (${r.lines})`);
  settings(["requirements.txt"]);
  writeFileSync(join(tmp, "requirements.txt"), "loose-moss>=1.0\n");
  r = await run(config, { root: tmp, base, get: npmGet, now: NOW });
  ok(r.code === 1 && mended(r.lines.join("\n")) && /requirements\.txt, line 1: a package not at one exact version/u.test(r.lines.join("\n")), `a file not in PyPI's lock form fails, saying the mend (${r.lines})`);
} finally { rmSync(tmp, { recursive: true, force: true }); }

console.log(failed ? `${failed} failing` : "ok   lookup-pypi.mjs");
process.exit(failed ? 1 : 0);
