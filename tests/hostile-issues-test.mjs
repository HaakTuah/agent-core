// Hostile tests of one input the core names under floor rule 5 (floor/topics/input.md): issues, their comments and
// their labels, which anyone can write and whose words count only from some accounts. Each reader is tried with what
// an attacker sends, as each case's shape allows: too long, the wrong type, markup, a file path, a number or date out
// of range, and nothing at all; each refuses, taking nothing of it as a pass or a value. The readers: labels.mjs,
// stand-in-record.mjs, review-record.mjs, and those of look.mjs and inbox.mjs that need no network. Test data is made
// up. Run by the core's tests workflow (.github/workflows/tests.yml). Node's own modules.
//
//   node tests/hostile-issues-test.mjs
import { spawnSync } from "../scripts/check-runs.mjs";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LIST, SINCE, cameOn, check, found, opens, strayViews, toMake } from "../scripts/labels.mjs";
import { entry, lacking, tally, verdict } from "../scripts/stand-in-record.mjs";
import { blockingOf, broughtBy, bugs, otherOf, perPull, postedKind, rulesIn } from "../scripts/review-record.mjs";
import { lastRun, mine, RECORD } from "../scripts/look.mjs";
import { answer, items, report, repoOf } from "../scripts/inbox.mjs";
import { scratchDir } from "../scripts/scratch-core.mjs";

let failed = 0;
const ok = (cond, what) => { console.log(`${cond ? "ok  " : "FAIL"} ${what}`); if (!cond) failed++; };

const owner = "an-owner", me = { login: "An-Owner" }, stranger = { login: "a-stranger" };
const sig = "\n\n---\n_Generated by [A Tool](https://example.invalid)_";
const late = "2026-12-01T10:00:00Z";
const all = Object.entries({ ...LIST.state, ...LIST.sender, ...LIST.mark }).map(([name, l]) => ({ name, ...l }));
const L = (...n) => n.map(name => ({ name }));
const sure = "The stand-in's verdict: yes, sure.";
const kinds = got => got.map(f => f.items.join());
const scratch = scratchDir("hostile-issues-test-");

// ---- too long ----
{
  const big = `${"* ".repeat(1 << 20)}\n${"#".repeat(1 << 20)} view\n${" \t".repeat(1 << 20)}x`; // (about 5 MB)
  const t0 = Date.now();
  const readers = [verdict(big), opens(big), found(big), strayViews(big).length, postedKind(big), blockingOf(big), otherOf(big), broughtBy(big), rulesIn(big).length];
  ok(Date.now() - t0 < 5000 && readers.every(r => r === null || r === false || r === 0),
    "a body of megabytes of stars, hashes and blanks is read in seconds, and holds no verdict, opener, line or count");
  const many = Array.from({ length: 20000 }, (_, k) => ({ number: k + 1, user: me, labels: L("queued", "by:owner"), body: "x", created_at: late }));
  many.push({ number: 20001, user: me, labels: L("by:owner"), body: big, created_at: late });
  const comments = Array.from({ length: 20000 }, (_, k) => ({ issue: k + 1, user: me, body: `Done.${sig}`, created_at: late, html_url: `u${k}` }));
  const t1 = Date.now(), got = check({ issues: many, comments, owner, have: all });
  ok(Date.now() - t1 < 5000 && got.length === 2 && got[0].items.join() === "#20001" && got[1].items.length === 20000,
    "twenty thousand issues and comments are read in seconds: the one with no state label and each agent's comment with no opener, named");
  const t2 = Date.now(), t = tally(Array.from({ length: 50000 }, (_, k) => ({ issue: k, at: late, body: k % 2 ? sure : big.slice(0, 64), writer: k % 4 === 1 })));
  ok(Date.now() - t2 < 5000 && t.verdicts["sure yes"] === 12500, "fifty thousand comments: only the owner's account's verdicts are counted, in seconds");
  const t3 = Date.now(), kept = mine(Array.from({ length: 20000 }, (_, k) => ({ number: k, user: k % 2 ? stranger : me, title: RECORD, state: "open", labels: [] })), owner);
  ok(Date.now() - t3 < 5000 && kept.get(RECORD).number === 19998 && kept.twins.length === 9999, "twenty thousand issues of one title: the newest of the owner's is the look's, a stranger's never");
}

// ---- the wrong type ----
for (const v of [5, {}, null, [], true]) {
  const what = JSON.stringify(v);
  const got = check({ issues: [{ number: 1, user: me, labels: L("queued", "by:owner"), body: v, created_at: late }, { number: 2, user: { login: v }, labels: L("queued"), body: v, created_at: late }],
    comments: [{ issue: 1, user: me, body: v, created_at: late, html_url: "u1" }], owner, have: all });
  ok(got.length === 0, `a body or login that is ${what} counts as none: no agent's issue or comment is read in it, and no sender asked of another account`);
  ok(verdict(v) === null && !opens(v) && !found(v) && strayViews(v).length === 0 && postedKind(v) === null && blockingOf(v) === null && broughtBy(v) === null,
    `a body that is ${what} holds no verdict, opener, line, review or count`);
  ok(kinds(check({ issues: [{ number: 3, user: me, labels: [{ name: v }, { name: "by:owner" }], body: "x", created_at: late }], owner, have: all })).join() === "#3",
    `a label whose name is ${what} counts as none: the issue still lacks its state label`);
  ok(tally([{ issue: 1, at: late, body: v, writer: true }]).comments === 1 && Object.keys(tally([{ issue: 1, at: late, body: v, writer: true }]).verdicts).length === 0,
    `a comment whose body is ${what} is counted as a comment and as no verdict`);
  const b = bugs([{ number: 1, at: late, login: v, body: "Brought in by: #2" }], [], new Map([[2, { when: "2026-11-01T00:00:00Z", kind: "own" }]]), owner);
  ok(b.filed === 0 && b.tied === 0 && b.others === 1, `a bug whose login is ${what} is another account's and ties nothing`);
  ok(mine([{ number: 1, user: { login: v }, title: RECORD, state: "open" }], owner).size === 0, `an issue whose login is ${what} is not one the look keeps`);
  ok(repoOf(v) === null && answer(v).yes === false, `an origin or a repository's answer that is ${what} reads as no`);
}
ok(lacking([{ issue: "1", title: "t", owner: "true" }, { issue: "2", title: "t", owner: 1 }], []).none.length === 0, "an idea's owner flag that is not true itself (\"true\", 1) is no idea of the owner's");
ok(answer({ has_issues: "true", permissions: { push: true } }).yes === false && answer({ has_issues: true, permissions: "push" }).yes === false && answer({ has_issues: true, permissions: null }).yes === false,
  "issues switched on as the text \"true\", or rights as a word or null, read as no");
ok(toMake([{ name: "queued", color: 0x0e8a16, description: LIST.state.queued.description }]).some(l => l.name === "queued" && l.how === "set"), "a colour given as a number is not taken as the list's: the label is set");
for (const [what, have] of [["null", null], ["an object", { queued: {} }], ["a text", "queued"], ["a list holding null, a number and a nameless label", [null, 5, { color: "0e8a16" }]]])
  ok(toMake(have).length === all.length && toMake(have).every(l => l.how === "make"), `the repository's labels given as ${what} are read as none held: every label is to make`);
for (const [what, labels] of [["null", null], ["a text", "queued"], ["an object", { name: "queued" }], ["a list holding null", [null, ...L("queued")]]]) {
  const on = l => { try { return JSON.stringify(check({ issues: [{ number: 4, user: me, labels: l, body: "x", created_at: late }], owner, have: all })); } catch (e) { return `threw ${e.name}`; } };
  ok(on(labels) === on(Array.isArray(labels) ? L("queued") : []), `an issue's labels given as ${what} throw nothing: what is no label counts as none`);
}

// ---- markup ----
ok(verdict(`> ${sure}`) === null && verdict(`\`\`\`\n${sure}\n\`\`\``) === null && verdict(`<!--\n${sure}\n-->`) === null, "a verdict quoted, in a code fence, or on a line of an HTML comment is none");
ok(["<!-- From a builder session: x -->", "<!--\nFrom a builder session: x\n-->", "> From a builder session: x", "```\nFrom a builder session: x\n```", "<script>From a builder session: x</script>", "> The stand-in's verdict: yes, sure."].every(b => !opens(b)),
  "an opener hidden in an HTML comment, quoted, fenced or in a script tag does not count");
ok(!found("> Found while: x") && !found("<script>Found while: x</script>"), "a \"Found while:\" line quoted or in a script tag does not count");
ok(["<!-- Security review: x -->", "> Security review: x", "```\nSecurity review: x\n```", "<script>Security review:</script>"].every(b => postedKind(b) === null), "a posted review's first line hidden, quoted, fenced or tagged is no review");
ok(blockingOf("Security review: x\n> Blocking findings: 0.") === null && broughtBy("> Brought in by: #5") === null, "a count or a \"Brought in by\" line quoted is not read");
ok(strayViews("## <script>view</script>").length === 1 && strayViews(`**${LIST.headings.view}<b></b>**`).length === 1, "a heading with markup in it is not the fixed view heading");
ok(kinds(check({ issues: [{ number: 1, user: me, labels: L("<b>queued</b>", "queued\u200b", "by:owner"), body: "x", created_at: late }], owner, have: all })).join() === "#1"
  && toMake([...all.filter(l => l.name !== "queued"), { name: "<b>queued</b>", color: "0e8a16", description: "" }]).map(l => l.name).join() === "queued",
  "a label named with markup or a hidden character is not the list's: the issue lacks its state, the label is still to make");
{
  const issue = { number: 9, user: me, labels: L("queued", "by:chat"), body: "**What it is**\nx", created_at: late };
  const notes = new Map([[9, [{ user: stranger, created_at: late, updated_at: late, body: `${sure}${sig}` }]]]);
  ok(check({ issues: [issue], notes, owner, have: all }).length === 0, "a stranger's sure yes, posted as an agent, marks nothing stand-in-yes");
  const cs = [{ issue: 9, user: stranger, body: `Done.${sig}`, created_at: late, html_url: "u" }, { issue: 9, user: stranger, body: `**My view**\nx${sig}`, created_at: late, html_url: "v" }];
  ok(check({ issues: [issue], comments: cs, owner, have: all }).length === 0, "a stranger's comment is never read as the owner's agent's");
}
ok(tally([{ issue: 1, at: late, body: sure, writer: false }]).verdicts["sure yes"] === undefined && lacking([{ issue: "1", title: "t", owner: false }], [{ issue: "1", at: late, body: "Take it up.", writer: false }]).others === 1,
  "a verdict or a taking-up from another account counts for nothing");
ok(perPull([{ user: stranger, body: "Security review: x\nBlocking findings: 0." }], [], owner).postedSecurity.got === false, "a posted review from another account is no review");
ok(entry({ issue: 1, title: "a\u0007b\u001b[31m<script>", owner: false }).includes("a b [31m<script>") && !/[\u0000-\u001f]/.test(entry({ issue: 1, title: "\r\n\u0000", owner: true }).trimStart()),
  "a title's control characters are taken out before it is printed; markup stays text");
ok(mine([{ number: 1, user: { login: "github-actions[bot]<script>" }, title: RECORD, state: "open" }], owner).size === 0, "a login with markup after the look's bot is not the bot");

// ---- a file path ----
for (const p of ["../../etc/passwd", "/etc/passwd", "C:\\Windows", "https://github.com/../../etc/passwd", "https://github.com/a/..", "file:///etc/passwd", "https://elsewhere.invalid/github.com/a/b"])
  ok(repoOf(p) === null, `an origin of ${p} names no repository on github.com`);
ok(broughtBy("Brought in by: #../../etc/passwd") === null && mine([{ number: 1, user: { login: "../../etc/passwd" }, title: RECORD, state: "open" }], owner).size === 0,
  "a path in place of a pull request's number or a login is neither");
{
  const inbox = path.join(scratch, "inbox");
  fs.mkdirSync(inbox);
  fs.writeFileSync(path.join(inbox, "a-task.md"), "x");
  // (Windows holds no file name with markup in it: there the blank alone is the odd one)
  const marked = process.platform !== "win32";
  if (marked) fs.writeFileSync(path.join(inbox, "<script>x.md"), "x");
  fs.writeFileSync(path.join(inbox, "a task.md"), "x");
  let linked = true;
  try { fs.symlinkSync("/etc/passwd", path.join(inbox, "passwd.md")); } catch { linked = false; }
  const got = items(scratch);
  ok(got.join() === "a-task.md" && got.odd === (marked ? 2 : 1), `the inbox's files: a name with markup or a blank is counted, not listed${linked ? ", and a link to /etc/passwd is no item" : ""}`);
  const said = report({ yes: false, why: "x" }, got, true);
  ok(!said.includes("<script>") && !said.includes("passwd"), "what the inbox prints names no odd file and no linked path");
}
{
  const run = (script, args) => spawnSync(process.execPath, [fileURLToPath(new URL(script, new URL("../scripts/", import.meta.url))), ...args], { cwd: scratch, encoding: "utf8", env: { ...process.env, PATH: path.join(scratch, "no-bin") } });
  for (const [script, args] of [["./labels.mjs", ["--since", "../../etc/passwd"]], ["./labels.mjs", ["--owner", "C:\\Windows"]], ["./stand-in-record.mjs", ["--repo", "../../etc/passwd"]], ["./stand-in-record.mjs", ["--owner", "/etc/passwd"]]]) {
    const r = run(script, args);
    ok(r.status === 1 && /^FAIL: /m.test(r.stderr) && !/\n\s+at /.test(r.stderr), `${path.basename(script)} ${args.join(" ")}: refused with one line, before anything is asked, and no stack`);
  }
}

// ---- a number or date out of range ----
for (const d of ["99999-01-01T00:00:00Z", "+099999-01-01T00:00:00Z", "-000001-01-01T00:00:00Z", "not a date", String(Number.MAX_SAFE_INTEGER + 2), "2026-13-45T99:99:99Z", "2027-02-30T00:00:00Z", "2027-01-01T24:00:00Z"]) {
  let got;
  try { got = cameOn(d); } catch (e) { got = `threw ${e.name}`; }
  ok(got === SINCE, `a day of ${d} moves the rule's day nowhere, and throws nothing`);
}
ok(lastRun("Last run: 99999-01-01T00:00:00Z") === null && lastRun("Last run: -1") === null, "a last run in year 99999, or negative, is none");
ok(["2026-13-45T99:99:99Z", "2027-02-30T00:00:00Z", "2027-01-01T24:00:00Z"].every(d => lastRun(`Last run: ${d}`) === null), "a last run on a day or at a time that cannot be (month 13, 30 February, hour 24) is none, so a missed run is never hidden by NaN");
ok(["Brought in by: #0", "Brought in by: #00", "Brought in by: #-5", "Brought in by: #9999999999", `Brought in by: #${Number.MAX_SAFE_INTEGER + 2}`, "Brought in by: #NaN"].every(b => broughtBy(b) === null),
  "a pull request's number nought, negative, past nine digits or not a number is none");
ok(blockingOf("Blocking findings: -1.") === null && blockingOf("Blocking findings: 9999999.") === null && blockingOf("Blocking findings: NaN.") === null,
  "a count of blocking findings negative, past six digits or not a number is not read");
{
  const merged = new Map([[7, { when: "+099999-01-01T00:00:00Z", kind: "own" }], [8, { when: "not a date", kind: "own" }]]);
  const b = bugs(["#7", "#8", "#6"].map((n, k) => ({ number: k + 1, at: late, login: owner, body: `Brought in by: ${n}` })), [], merged, owner);
  ok(b.tied === 0 && b.unmatched === 3, "a bug tied to a pull request merged in year 99999, at no readable time, or never read, ties to none");
}

// ---- nothing at all ----
for (const v of [undefined, null, ""]) {
  ok(verdict(v) === null && !opens(v) && !found(v) && strayViews(v).length === 0 && postedKind(v) === null && blockingOf(v) === null && otherOf(v) === null
    && broughtBy(v) === null && rulesIn(v).length === 0 && lastRun(v) === null && repoOf(v) === null && answer(v).yes === false && cameOn(v) === SINCE,
  `a body of ${JSON.stringify(v)} holds nothing and throws nothing`);
}
ok(check({ issues: [], owner, have: all }).length === 0 && kinds(check({ issues: [], owner, have: [] }))[0].split(",").length === all.length,
  "no issues and every label: nothing to mend; no labels: each of the list to make");
ok(tally([]).comments === 0 && lacking([], []).none.length === 0 && bugs([], [], new Map(), owner).filed === 0 && mine([], owner).size === 0,
  "no comments, ideas, bugs or issues: every count is zero");
ok(perPull([], [], owner).postedSecurity.got === false && perPull([], [], owner).codexCode.got === false, "a pull request with no comments got no review");
ok(items(path.join(scratch, "none")).length === 0 && /could not be asked/.test(report(null, items(path.join(scratch, "none")), false)), "no inbox folder and no answer: no item, and nothing moves");

process.exit(failed ? 1 : 0);
