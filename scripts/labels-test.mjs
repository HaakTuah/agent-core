// Tests of the labels and openers (labels.mjs): the list's shape, an agent's attribution line, a comment's opening line,
// the "Found while:" line, a view's heading, the labels to make, what the check reports of each kind and of none; and,
// on Linux and macOS, the script itself where gh gives no answer, which reports that and fails nothing, and the day it
// reads from in a full clone, a shallow one and where git cannot start. Node's own modules and git.
//
//   node scripts/labels-test.mjs
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LIST, SENDERS, SEVERAL, SINCE, STATES, byAgent, cameOn, check, found, opens, report, strayViews, toMake } from "./labels.mjs";
import { SENDERS as FILE_SENDERS, STATES as FILE_STATES } from "./inbox.mjs";

let failed = 0, count = 0;
const ok = (cond, what, detail = "") => { count++; if (cond) console.log(`ok   ${what}`); else { failed++; console.error(`FAIL ${what}${detail && `\n     ${detail}`}`); } };

ok(STATES.join() === "queued,needs-owner,later,on-hold" && SENDERS.length === 8 && SENDERS.every(s => s.startsWith("by:")),
  "the list: four states and eight senders", `${STATES} ${SENDERS}`);
ok(Object.values({ ...LIST.state, ...LIST.sender, ...LIST.mark }).every(l => /^[0-9a-f]{6}$/.test(l.color) && l.description.length <= 100),
  "each label has a colour GitHub takes and a description of at most 100 characters");
ok(FILE_STATES.join() === STATES.join() && FILE_SENDERS.join() === SENDERS.map(s => s.slice(3)).join(),
  "the inbox's two lines take the same names, a sender without its by:");

const sig = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
ok(byAgent(`text${sig}`) && byAgent("x\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)") && byAgent("x\nGenerated by [Another Tool](https://example.invalid)"),
  "an agent's attribution line, in each form a tool writes it");
ok(!byAgent("The owner's own words.") && !byAgent("It was Generated by [hand] in a sentence."), "no attribution line: the owner's own");

ok(["From a builder session, on #241: the fix.", "From the orchestrator:", "Security review: none needed for abc.", "Taken in: > the owner's words", "@codex review", "@codex security review",
  "The stand-in's verdict: yes, sure.", "\n\nDesign check: read at abc"].every(opens), "each opener of the list, with a task, the stand-in's verdict and a call to a reviewer");
ok(!["From the builder of #238 (#287): two points", "On review rounds: six", "**From a builder session:**", "From a builder session on #241:", "> The stand-in's verdict: yes"].some(opens),
  "an opener not on the list, in another spelling or quoted does not count");

ok(found("**What it is**\nx\n\nFound while: fixing #241 (a builder session)") && found("**Found while:** the security review of #262") && !found("It was found while fixing #241."),
  "the \"Found while:\" line, plain or in bold, never in a sentence");
ok(!found("**What it is**\nx\n<!--\nFound while: fixing #241\n-->") && !found("x\n```\nFound while: fixing #241\n```") && found("<!-- a note -->\nFound while: fixing #241"),
  "a \"Found while:\" line hidden from the reader, in an HTML comment or a fenced block, is none");
ok(strayViews("**The session's view (not a decision)**\nA builder may weigh it.").length === 0 && strayViews("**My view**\nx\n## The session's view\ny").length === 2
  && strayViews("**What it is**\nThe owner's view is quoted.").length === 0,
  "a heading that names a view is the fixed one; a view named in a sentence is not a heading");

const t0 = Date.now(), long = `# a${" ".repeat(65000)}#${" ".repeat(65000)}x`;
strayViews(long); strayViews(`**${" ".repeat(65000)}`); found("\n".repeat(65000)); opens(`The stand-in's verdict${" \t".repeat(32000)}x`); opens(`The stand-in's verdict${"*".repeat(65000)}x`); byAgent(`${"_ ".repeat(40000)}\n`.repeat(2));
ok(Date.now() - t0 < 2000, "a body of any shape, the longest GitHub keeps, is read in time in step with its length", `${Date.now() - t0} ms`);

const have = [{ name: "Queued", color: "0e8a16", description: LIST.state.queued.description }, { name: "later", color: "000000", description: LIST.state.later.description },
  ...Object.entries({ ...LIST.state, ...LIST.sender, ...LIST.mark }).filter(([n]) => !["queued", "later", "by:look"].includes(n)).map(([name, l]) => ({ name, ...l })), { name: "bug", color: "d73a4a", description: "x" }];
const todo = toMake(have);
ok(todo.map(l => `${l.name}:${l.how}`).join() === "queued:set,later:set,by:look:make" && todo[0].was === "Queued",
  "the labels to make: one missing; set: another colour, or a name in another case; another label untouched", JSON.stringify(todo));
const all = Object.entries({ ...LIST.state, ...LIST.sender, ...LIST.mark }).map(([name, l]) => ({ name, ...l }));
ok(toMake(all).length === 0, "every label as the list says: none to make");

const owner = "someone", me = { login: "Someone" }, other = { login: "another" }, late = "2026-12-01T10:00:00Z", early = "2026-11-01T10:00:00Z";
const L = (...n) => n.map(name => ({ name }));
const issues = [
  { number: 1, user: me, labels: L("queued", "by:chat"), body: "**What it is**\nx", created_at: early },
  { number: 2, user: me, labels: L("by:builder"), body: `x${sig}`, created_at: early },
  { number: 3, user: me, labels: L("queued", "later", "by:builder"), body: `Found while: a sync${sig}`, created_at: late },
  { number: 4, user: me, labels: L("needs-owner"), body: "The owner's own.", created_at: early },
  { number: 5, user: other, labels: L("needs-owner"), body: "An outsider's idea.", created_at: late },
  { number: 6, user: me, labels: L("queued", "by:reviewer"), body: `What a review found.${sig}`, created_at: late },
  { number: 7, user: me, labels: L("queued", "by:chat"), body: `**My view**\nx${sig}`, created_at: late },
];
const comments = [
  { issue: 1, user: me, body: `From a builder session, on #1: done.${sig}`, created_at: late, html_url: "u1" },
  { issue: 1, user: me, body: `Done.${sig}`, created_at: late, html_url: "u2" },
  { issue: 1, user: me, body: `Done, before the rule.${sig}`, created_at: early, html_url: "u3" },
  { issue: 1, user: me, body: "The owner's own comment.", created_at: late, html_url: "u4" },
  { issue: 1, user: other, body: `Someone else.${sig}`, created_at: late, html_url: "u5" },
  { issue: 7, user: me, body: `From a chat session with the owner:\n\n**This session's view**\nx${sig}`, created_at: late, html_url: "u6" },
];
const note = (at, body) => ({ user: me, created_at: at, updated_at: at, body: `${body}${sig}` });
const chat = "From a chat session with the owner:\n\nA note.";
const notes = new Map([
  [1, [note("2026-11-14T01:00:00Z", chat), note("2026-11-14T02:00:00Z", chat), note("2026-11-14T03:00:00Z", chat), note("2026-11-14T04:00:00Z", `From a builder session: a detail.`)]],
  [6, [{ ...note("2026-11-14T01:00:00Z", `${chat}\n${LIST.headings.current}`), updated_at: "2026-11-14T09:00:00Z" }, note("2026-11-14T02:00:00Z", chat), note("2026-11-14T03:00:00Z", chat), note("2026-11-14T04:00:00Z", chat)]],
  [7, [note("2026-11-14T01:00:00Z", `${chat}\n${LIST.headings.current}`), note("2026-11-14T02:00:00Z", chat)]],
]);
const got = check({ issues, comments, notes, owner, have: all });
const kind = word => got.find(f => f.what.includes(word))?.items.join() ?? "";
ok(kind("One state label") === "#2,#3", "a state label missing or doubled is reported; an outsider's issue needs one too", kind("One state label"));
ok(kind("One sender label") === "#4", "a sender label missing on the owner's account's issue; none asked of another account's", kind("One sender label"));
ok(kind("Found while") === "#6,#7", "an agent's issue since the rule came lacks its \"Found while:\" line, a chat session's too; one from before, or the owner's own, is not asked", kind("Found while"));
ok(kind("opening line") === "u2", "an agent's comment since the rule came with no opener; one from before, the owner's own and another account's are not read", kind("opening line"));
ok(kind("view in an item") === "#7,u6", "a view under another heading, in an item of the owner's voice and in an agent's note on it", kind("view in an item"));
ok(kind("current text") === "#1", `${SEVERAL} notes in the owner's voice after the description are reported; a current text edited after its notes, or one with fewer after it, is not`, kind("current text"));
ok(!kind("labels of the list"), "every label stands: none to make is reported");
ok(check({ issues, comments, notes, owner, have: all, since: "2027-01-01" }).every(f => !/Found while|opening line|view in/.test(f.what)), "--since moves when items and comments are read from");
const clean = check({ issues: [issues[0]], comments: [comments[0]], owner, have: all });
ok(clean.length === 0 && /every label of the list stands/.test(report(clean, "someone/x")), "nothing to mend: one line that says so");
ok(/^The labels and openers in someone\/x \(core\/scripts\/labels\.mjs\): \d kind\(s\) to mend/.test(report(got, "someone/x")) && /nothing fails/.test(report(got, "someone/x")),
  "the report says what to mend and that nothing fails");
ok(cameOn("") === SINCE && cameOn("2026-11-10T09:00:00+00:00") === SINCE && cameOn("2027-02-01T10:00:00+01:00\n2027-01-05T08:00:00Z") === "2027-02-01T09:00:00Z" && cameOn("not a date") === SINCE,
  "items and comments are read from the day the project's copy gained the check, never before the rule came", cameOn("2027-02-01T10:00:00+01:00\n2027-01-05T08:00:00Z"));
ok(/another account's issue needs-owner/.test(got.find(f => f.what.includes("One state label")).what), "the state's mend names one for another account's issue too");

const yes = note("2026-11-14T05:00:00Z", "**The stand-in's verdict: yes, sure.** Cheap and exact.");
const marked = check({ owner, have: all, notes: new Map([[8, [yes]], [9, [yes, { user: me, created_at: "2026-11-14T06:00:00Z", body: "The owner's own: yes." }]], [10, [yes, note("2026-11-14T06:00:00Z", "From a builder session, on #10: started.")]], [11, [yes]]]),
  issues: [8, 9, 10, 11].map(number => ({ number, user: me, labels: L("queued", "by:builder", ...(number === 9 || number === 11 ? ["stand-in-yes"] : [])), body: "x", created_at: early })) });
ok(marked.find(f => f.what.includes("stand-in-yes"))?.items.join() === "#8 (to mark),#10 (to mark),#9 (to take off)",
  "queued on the stand-in's sure yes: marked until a note in the owner's voice follows, and the mark taken off once one does; an agent's note changes nothing",
  JSON.stringify(marked));

// The script where gh gives no answer: it says so and fails nothing.
if (process.platform !== "win32") {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "labels-test-"));
  try {
    const bin = path.join(tmp, "bin"), repo = path.join(tmp, "repo");
    fs.mkdirSync(bin); fs.mkdirSync(repo);
    fs.writeFileSync(path.join(bin, "gh"), "#!/bin/sh\necho 'invalid config file /home/a-person/.config/gh/config.yml' >&2\nexit 1\n", { mode: 0o755 });
    spawnSync("git", ["init", "-q"], { cwd: repo });
    spawnSync("git", ["remote", "add", "origin", "https://github.com/someone/a-game"], { cwd: repo });
    const script = path.join(path.dirname(fileURLToPath(import.meta.url)), "labels.mjs");
    const env = { ...process.env, PATH: `${bin}${path.delimiter}${process.env.PATH}` };
    const r = spawnSync(process.execPath, [script], { cwd: repo, env, encoding: "utf8" });
    ok(r.status === 0 && /could not be read here/.test(r.stdout) && !/a-person|config\.yml/.test(`${r.stdout}${r.stderr}`), "where gh gives no answer, it says so and fails nothing, and prints none of gh's words, which may name a path of the machine", `${r.stdout}${r.stderr}`);
    const m = spawnSync(process.execPath, [script, "--make"], { cwd: repo, env, encoding: "utf8" });
    ok(m.status === 0 && /could not be read here/.test(m.stdout), "--make where gh gives no answer makes nothing and fails nothing", `${m.stdout}${m.stderr}`);
    const bad = spawnSync(process.execPath, [script, "--since", "soon"], { cwd: repo, env, encoding: "utf8" });
    ok(bad.status === 1 && /--since needs a date/.test(bad.stderr), "a wrong option fails, saying what it takes");
  } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
}

// The day the rule came for the copy here (sinceHere): from git's history, in a shallow clone and with no git at all.
if (process.platform !== "win32") {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "labels-since-"));
  try {
    const full = path.join(tmp, "full"), env = { ...process.env, GIT_CONFIG_GLOBAL: path.join(tmp, "none"), GIT_CONFIG_NOSYSTEM: "1", GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@example.invalid", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@example.invalid" };
    const git = (cwd, date, ...a) => spawnSync("git", a, { cwd, env: { ...env, GIT_AUTHOR_DATE: date, GIT_COMMITTER_DATE: date }, encoding: "utf8" });
    fs.mkdirSync(full);
    git(full, "", "init", "-q", "-b", "main");
    const commit = (date, file) => { fs.mkdirSync(path.dirname(path.join(full, file)), { recursive: true }); fs.writeFileSync(path.join(full, file), date); git(full, date, "add", "-A"); git(full, date, "commit", "-q", "-m", date); };
    commit("2027-01-05T08:00:00Z", "a.txt");
    commit("2027-01-20T09:00:00Z", "b.txt");
    commit("2027-02-01T09:00:00Z", "core/scripts/labels.mjs");
    commit("2027-04-01T09:00:00Z", "c.txt");
    const since = (cwd, extra = {}) => spawnSync(process.execPath, ["--input-type=module", "-e", `import { sinceHere } from ${JSON.stringify(new URL("./labels.mjs", import.meta.url).href)}; console.log(sinceHere());`], { cwd, env: { ...env, ...extra }, encoding: "utf8" }).stdout.trim();
    ok(since(full) === "2027-02-01T09:00:00Z", "from the day git's history shows the copy gained the check", since(full));
    const deep = path.join(tmp, "deep"), shallow = path.join(tmp, "shallow");
    git(tmp, "", "clone", "-q", "--depth", "3", `file://${full}`, deep);
    git(tmp, "", "clone", "-q", "--depth", "1", `file://${full}`, shallow);
    ok(since(deep) === "2027-02-01T09:00:00Z", "a shallow clone whose history holds the add reads it", since(deep));
    ok(since(shallow) === SINCE, "a shallow clone that shows the file only on its boundary commit reads the rule's own day, never a later one", since(shallow));
    const noGit = path.join(tmp, "no-git");
    fs.mkdirSync(noGit);
    fs.symlinkSync(process.execPath, path.join(noGit, "node"));
    ok(since(full, { PATH: noGit }) === SINCE, "where git cannot start, the rule's own day", since(full, { PATH: noGit }));
  } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
}

console.log(`\n${count - failed} of ${count} passed`);
process.exitCode = failed ? 1 : 0;
